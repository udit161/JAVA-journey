public class Main {
    public static void main(String[] args) {

        String day = "Wednesday";

        switch (day) {
            case "Monday":
                System.out.println("It is a weekday");
                break;
            case "Tuesday":
                System.out.println("It is a weekday");
                break;
            case "Wednesday":
                System.out.println("It is the day you were born!!!");
                break;
            case "Thursday":
                System.out.println("It is a weekday");
                break;
            case "Friday":
                System.out.println("It is a weekday");
                break;
            case "Saturday":
                System.out.println("It is a weekend");
                break;
            case "Sunday":
                System.out.println("It is a weekend");
                break;
        }
    }

}
